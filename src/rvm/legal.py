"""Юридический фильтр (ст. 64, 86, 88 ТК): темы, о которых работодатель не спрашивает
и которые не называет причиной отказа. Срабатывает с запасом: лишний отброшенный вопрос
дешевле незаконного."""

import re

# текст сравнивается в нижнем регистре, «ё» → «е»
TOPICS: dict[str, re.Pattern[str]] = {
    name: re.compile(pattern)
    for name, pattern in {
        "дети": r"\bдет(и|ей|ям|ьми|ях|ск\w*)\b|ребен|декрет|материнств|отцовств",
        "беременность": r"беремен",
        "брак и семья": r"\bв браке\b|\bбрак(а|ом|е)? (с|у)\b|женат|замуж|супруг|\bразвод"
        r"|\bсем(ья|ьи|ье|ью|ьей|ейн\w*)\b|\bмуж(а|у|ем)?\b|\bжен(а|ы|е|у|ой)\b",
        "здоровье и инвалидность": r"здоров(ь|ы|ая|ое|ом)|болезн|болеете|больничн|инвалид"
        r"|хроническ|диагноз|\bовз\b|ограниченн\w* возможност|лекарств",
        "религия": r"религ|вероисповед|верующ|\bвер(а|у|ы|ой)\b|церк|мечет|конфесс",
        "национальность и происхождение": r"национальност|происхожд|этническ|\bэтнос|\bрас(а|ы|ой)\b"
        r"|родной язык|\bродом\b",
        "возраст": r"возраст|сколько (вам )?лет|лет вам|год\w* рождения|дат\w* рождения"
        r"|когда вы родил",
        "судимость": r"судим|уголовн|привлекал\w* к \w*ответственн",
        "политика и членство в организациях": r"политич|\bпарти(я|и|ю|ей|й)\b|профсоюз|членств"
        r"|состоите ли вы в|голосовал|митинг",
        "сексуальная ориентация": r"сексуальн|гомосексуал|\bлгбт|\bгей\b",
        "внешность": r"внешност|\bваш (рост|вес)\b|\bрост и вес|\bвесите\b|как вы выглядите"
        r"|привлекательн",
    }.items()
}


def topic(text: str) -> str | None:
    """Первая запрещённая тема в тексте или None."""
    norm = text.lower().replace("ё", "е")
    return next((name for name, rx in TOPICS.items() if rx.search(norm)), None)


def lawful(texts: list[str]) -> tuple[list[str], int]:
    """Оставить тексты без запрещённых тем; второе — сколько отброшено."""
    kept = [t for t in texts if topic(t) is None]
    return kept, len(texts) - len(kept)
